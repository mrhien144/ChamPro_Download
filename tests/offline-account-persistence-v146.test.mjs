import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const f=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const account=f('android-build/account-direct.mjs');
const license=f('android-build/offline-license.mjs');
const native=f('android-build/native-app.js');
const builder=f('android-build/prepare-preview-apk.py');
assert(account.includes("verifyLicense(saved).then(claim=>{") && account.includes("unlock(claim);"),'active offline signed license must work without fetch');
assert(account.includes("inspectSignedIdentity(saved)"),'verified identity must be retained when license expires');
assert(/function unlock\(claim\)\{\s*verified=claim;\s*announceIdentity\(claim\);/.test(account),'verified account must be announced to the sync controller on unlock');
assert(account.includes("if(identity)"),'offline account identity shown separately from entitlement');
assert(!account.includes("localStorage.removeItem(LICENSE_KEY);verified=null;lock();stamp('Đăng nhập"),'no silent automatic logout');
assert(account.includes("if(!confirm('Đăng xuất trên thiết bị này?"),'logout must be explicit');
assert(license.includes("async function inspectSignedIdentity(")&&license.includes("crypto.subtle.verify("));
assert(license.includes("return {sub:body.sub,plan:body.plan"),'signature-only identity used for display');
assert(license.includes("body.exp<=now"),'paid rights must still expire correctly');
assert(!native.includes('Bản thử nghiệm'),'native banner must be official');
assert(builder.includes("s = s.replace('BẢN THỬ NGHIỆM RIÊNG'"),'APK-only copy changes');
assert(builder.includes('Đồng bộ giữa điện thoại và ChấmPro Web chưa kích hoạt'),'do not falsely claim live sync');
assert(builder.includes('Đăng nhập')||builder.includes('Tài khoản'));
console.log('PASS: offline account stays remembered, expired rights locked, no misleading trial banners.');
