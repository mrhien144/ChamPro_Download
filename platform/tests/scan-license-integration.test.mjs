import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const app=readFileSync('app/app.mjs','utf8');
const html=readFileSync('app/index.html','utf8');
const license=readFileSync('platform/licensing/scan-license.js','utf8');
const auto=app.indexOf('async function readCanvas('),scanEnd=app.indexOf('async function autoScanOnce(');
const authorized=app.indexOf('async function saveResultAuthorized('),commit=app.indexOf('function saveResult(');
assert(auto>=0&&scanEnd>auto&&authorized>scanEnd&&commit>authorized);
assert(app.slice(auto,scanEnd).includes('await saveResultAuthorized(exam,student,result,true)'));
assert(!app.slice(auto,app.indexOf('const fingerprint=',auto)).includes('.charge('),'OMR should not charge while recognizing frames');
assert(app.includes("const done=await saveResultAuthorized(exam,student,answers,false)"));
const authBody=app.slice(authorized,commit);
assert(authBody.indexOf('await license.charge(fingerprint)')<authBody.indexOf('const saved=saveResult('));
assert(authBody.includes("pendingAnonymousScanKeys.set(anonymousKey,id())"),'anonymous papers require separate IDs');
assert(html.includes('id="scanLicenseStatus"')&&html.includes('id="scanLicenseLogin"'));
assert(html.indexOf('auth-session.js')<html.indexOf('scan-license.js'));
assert(license.includes('session?.getToken()')&&license.includes('session?.save(event.data.token)'));
assert(!app.includes('CHAMPRO_LIVE_GRANTS_ENABLED'),'web scan app cannot open payment grants');
console.log('PASS: scan authorization follows recognition, guards both save paths, and leaves camera decoding unchanged.');
